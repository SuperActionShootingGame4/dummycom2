/* ---- selected config ------------------------------------------------- */
#if AUDIO_OUT_MODE == AUDIO_OUT_DAC48K
static uint32_t s_L = 6;
static const float (*s_coef)[DSP_TAPS_PER_PHASE] = s_coef_x6;
#else
static uint32_t s_L = 2;
static const float (*s_coef)[DSP_TAPS_PER_PHASE] = s_coef_x2;
#endif

/* ---- filter state -------------------------------------------------- */
static float s_hpf_a  = 0.90f;   /* one-pole high-pass coefficient (rate-dependent) */
static float s_hpf_x1 = 0.0f;
static float s_hpf_y1 = 0.0f;
static float s_hist[DSP_TAPS_PER_PHASE];   /* FIR input history, s_hist[0] = newest */

/* ---- gate state --------------------------------------------------- */
static float s_env       = 0.0f;   /* signal envelope (peak-hold, exp release) */
static float s_gain      = 1.0f;   /* current gate gain, slews toward target */
static float s_env_rel   = 0.01f;  /* envelope release coefficient */
static float s_gain_up   = 0.5f;   /* gain slew coefficient when opening */
static float s_gain_down = 0.02f;  /* gain slew coefficient when closing */
static uint32_t s_hold_max   = 2000;
static uint32_t s_hold_count = 0;

static float onepole_coef(float tau_ms, uint32_t fs)
{
    /* 1 - exp(-1 / (tau * fs)) : per-sample coefficient for a one-pole toward target */
    float k = 1.0f - expf(-1.0f / ((tau_ms * 0.001f) * (float)fs));
    if (k < 0.0f) k = 0.0f;
    if (k > 1.0f) k = 1.0f;
    return k;
}

void audio_dsp_set_input_rate(uint32_t hz)
{
#if AUDIO_OUT_MODE == AUDIO_OUT_DAC48K
    if (hz == 16000) {
        s_L = 3;
        s_coef = s_coef_x3;
    } else if (hz == 8000) {
        s_L = 6;
        s_coef = s_coef_x6;
    } else {
        return;                         /* unsupported - keep current config */
    }
#else
    if (hz == 16000) {
        s_L = 1;                        /* pass-through: input rate == output rate */
    } else if (hz == 8000) {
        s_L = 2;
        s_coef = s_coef_x2;
    } else {
        return;                         /* unsupported - keep current config */
    }
#endif
    s_hpf_a = (AUDIO_HPF_CUTOFF_HZ > 0.0f)
              ? expf(-2.0f * (float)M_PI * AUDIO_HPF_CUTOFF_HZ / (float)hz)
              : 1.0f;                    /* a == 1 -> pure DC blocker */

    s_env_rel   = onepole_coef(AUDIO_GATE_ENV_REL_MS, hz);
    s_gain_up   = onepole_coef(AUDIO_GATE_ATTACK_MS, hz);
    s_gain_down = onepole_coef(AUDIO_GATE_RELEASE_MS, hz);
    s_hold_max  = (uint32_t)(((uint64_t)AUDIO_GATE_HOLD_MS * hz) / 1000u);

    audio_dsp_reset();
}

void audio_dsp_reset(void)
{
    s_hpf_x1 = 0.0f;
    s_hpf_y1 = 0.0f;
    memset(s_hist, 0, sizeof(s_hist));
    s_env = 0.0f;
#if AUDIO_GATE_ENABLE
    s_gain = AUDIO_GATE_FLOOR;           /* start closed; first speech opens it */
#else
    s_gain = 1.0f;
#endif
    s_hold_count = 0;
}

uint32_t audio_dsp_upsample_factor(void)
{
    return s_L;
}

uint32_t audio_dsp_process(const int16_t *in, uint32_t n_in,
                           int16_t *out, uint32_t out_cap)
{
    const uint32_t L = s_L;
    if (n_in > out_cap / L) {
        n_in = out_cap / L;             /* never overrun the caller's buffer */
    }

    uint32_t o = 0;
    for (uint32_t i = 0; i < n_in; i++) {
        /* 1. one-pole DC-blocking high-pass: y = a * (y1 + x - x1) */
        float x = (float)in[i];
        float y = s_hpf_a * (s_hpf_y1 + x - s_hpf_x1);
        s_hpf_x1 = x;
        s_hpf_y1 = y;

#if AUDIO_GATE_ENABLE
        /* 2. noise gate: peak-hold envelope, open instantly, release slowly */
        float mag = fabsf(y);
        if (mag > s_env) {
            s_env = mag;
        } else {
            s_env += (mag - s_env) * s_env_rel;
        }

        float target;
        if (s_env >= AUDIO_GATE_OPEN_LEVEL) {
            target = 1.0f;
            s_hold_count = s_hold_max;
        } else if (s_hold_count > 0) {
            target = 1.0f;
            s_hold_count--;
        } else {
            target = AUDIO_GATE_FLOOR;
        }

        float slew = (target > s_gain) ? s_gain_up : s_gain_down;
        s_gain += (target - s_gain) * slew;
        y *= s_gain;
#endif

#if AUDIO_OUT_MODE == AUDIO_OUT_I2S16K
        if (L == 1) {                   /* 16 kHz in == 16 kHz out: no interpolation */
            int32_t v = (int32_t)lrintf(y);
            if (v > 32767) {
                v = 32767;
            } else if (v < -32768) {
                v = -32768;
            }
            out[o++] = (int16_t)v;
            continue;
        }
#endif

        /* shift into FIR history (s_hist[0] = newest) */
        for (int k = DSP_TAPS_PER_PHASE - 1; k > 0; k--) {
            s_hist[k] = s_hist[k - 1];
        }
        s_hist[0] = y;

        /* 3. polyphase interpolation: L output samples per input sample */
        for (uint32_t p = 0; p < L; p++) {
            const float *h = s_coef[p];
            float acc = 0.0f;
            for (uint32_t k = 0; k < DSP_TAPS_PER_PHASE; k++) {
                acc += h[k] * s_hist[k];
            }
            int32_t v = (int32_t)lrintf(acc);
            if (v > 32767) {
                v = 32767;
            } else if (v < -32768) {
                v = -32768;
            }
            out[o++] = (int16_t)v;
        }
    }
    return o;
}
